local H = require("helpers")

describe("loading", function()
  it("loads the bundled variants with background and colors_name", function()
    H.setup()
    vim.cmd.colorscheme("vale-night")
    eq("vale-night", vim.g.colors_name)
    eq("dark", vim.o.background)
    local night = H.normal_bg()
    vim.cmd.colorscheme("vale-day")
    eq("vale-day", vim.g.colors_name)
    eq("light", vim.o.background)
    ok(night ~= H.normal_bg(), "the variants use different palettes")
  end)

  it("builds a statusline theme for each variant", function()
    H.setup()
    vim.cmd.colorscheme("vale-night")
    local theme = require("lualine.themes.vale-night")
    ok(theme.normal and theme.normal.a and theme.normal.a.bg, "normal mode badge")
  end)

  it("layers theme semantics over the shared default", function()
    local vale = H.setup()
    local _, c, r = vale.build("vale", "night")
    eq(c[require("vale.semantics").string], r.string)
    local _, _, day = vale.build("vale", "day")
    local _, dc = vale.build("vale", "day")
    eq(dc.amber, day.folder, "vale's own semantics.lua re-points folder for day")
  end)
end)

describe("theme directories", function()
  it("prefers the user's copy of a theme over the bundled one", function()
    local vale = H.setup()
    vim.cmd.colorscheme("vale-night")
    local bundled_bg = H.normal_bg()
    vale.copy_to_user("vale")
    local path = H.config .. "/themes/vale/night.lua"
    local lines = require("vale.studio.writer").apply(vim.fn.readfile(path), { ["base.bg"] = "#010203" })
    vim.fn.writefile(assert(lines), path)
    vim.cmd.colorscheme("vale-night")
    eq("#010203", H.normal_bg())
    ok(bundled_bg ~= "#010203")
  end)

  it("lists bundled and user themes, each once", function()
    local vale = H.setup()
    ok(vim.tbl_contains(vale.colorschemes(), "vale-night"))
    ok(vim.tbl_contains(vale.colorschemes(), "vale-day"))
    eq(true, vale.list()[1].bundled)
    vale.copy_to_user("vale")
    local count = #vim.tbl_filter(function(name)
      return name == "vale-night"
    end, vale.colorschemes())
    eq(1, count)
    eq(false, vale.list()[1].bundled)
  end)

  it("defaults to the configuration directory", function()
    local vale = require("vale")
    vale.setup()
    eq(vim.fs.joinpath(vim.fn.stdpath("config"), "themes"), vale.themes_dir())
    eq(vim.fn.stdpath("config"), vale.options.output_dir)
  end)
end)
